
import argparse
import json
from pathlib import Path

RUN_ID = "20261115T113239215880Z"

BASE_DIR = Path(__file__).resolve().parents[2]

CHUNK_FILES = {
    "fixed_size": "fixed_size_chunks.json",
    "recursive": "recursive_chunks.json",
    "semantic": "semantic_chunks.json",
    "structure": "structure_chunks.json",
    "logical_unit": "logical_unit_chunks.json",
}


def main():
    parser = argparse.ArgumentParser(
        description="Inspect chunks generated by a chunking strategy."
    )
    parser.add_argument(
        "strategy",
        choices=CHUNK_FILES.keys(),
        help="Chunking strategy to inspect."
    )
    parser.add_argument(
        "--index",
        type=int,
        default=0,
        help="Zero-based chunk index to inspect."
    )

    args = parser.parse_args()

    file_path = (
        BASE_DIR / "experiments" / "results"
        / "chunk_statistics" / RUN_ID
        / CHUNK_FILES[args.strategy]
    )

    with open(file_path, "r", encoding="utf-8") as file:
        data = json.load(file)

    chunks = data["chunks"]

    print("Strategy:", data.get("strategy"))
    print("Total chunks:", len(chunks))

    if not 0 <= args.index < len(chunks):
        raise IndexError(
            f"Chunk index {args.index} is out of range. "
            f"Valid range: 0 to {len(chunks) - 1}"
        )

    print(f"\nChunk {args.index}:")
    print(json.dumps(
        chunks[args.index],
        indent=4,
        ensure_ascii=False
    ))


if __name__ == "__main__":
    main()
